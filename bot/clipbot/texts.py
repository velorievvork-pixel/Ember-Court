def clips_word(n: int) -> str:
    """1 клип, 2 клипа, 5 клипов."""
    form = "клипов" if 11 <= n % 100 <= 14 else {1: "клип", 2: "клипа", 3: "клипа", 4: "клипа"}.get(n % 10, "клипов")
    return f"{n} {form}"
